// The real Vircon32 BIOS font (10x20 pixels, full 256-glyph codepage-1252
// layout) - the same font the Vircon32 build's own menu.c drew its text
// with via the BIOS's built-in print_at() (see menu.h's note in that
// project: "this project draws menu text with Vircon32's own built-in BIOS
// font... since there is no shared sprite-font engine here"). No SDL
// equivalent of print_at() exists, so this reproduces the actual glyph
// bitmaps as data instead - per direct user request to match the BIOS
// font specifically, not reuse one of the in-project game fonts.
//
// Source: the Vircon32 project's own font asset, authored by "Carra"
// (the Vircon32 project's own author) - found locally at
// C:\github\ConsoleSoftware\Bios\StandardBios\font 10x20 (codepage 1252)\
// Font 10x20 Bios Vircon32.png (also published on OpenGameArt.org as
// "Pixel Art Outlined Text Fonts", CC-BY 4.0). Confirmed as the exact
// glyph size/layout the real BIOS uses by reading StandardBios.c's own
// `define_region_matrix(first_region_font, 1,22, 10,41, 1,22, 32,8, 0)`
// call (glyph box 1..10 x 22..41 inclusive = 10x20 pixels).
//
// Extracted from the PNG (16 columns x 16 rows of 10x20 glyphs, raster
// order = codepage-1252 byte value 0-255, no gap) via a one-off Python
// script (ImageMagick `txt:` pixel dump -> per-column 20-bit bitmask,
// bit0 = topmost pixel of the glyph) - biosFont10x20[ch][col], not a
// hand-transcription, so there's no risk of the manual-transcription bugs
// this project has hit before with large data tables.
//
// Unlike menuFont.h's 6x8 one-byte-per-column font (still used by every
// *game* that needs its own font - Oroboros/Run Dude Run/Dino Game - since
// their glyphs are page-aligned 8px tall), this font's glyphs are 20px
// tall and don't line up with an 8px SSD1306 "page" at all, so it's drawn
// via md_drawColumnPixels() (an absolute-pixel-row primitive, not
// md_drawColumn()'s page-based one) instead.
// -----------------------------------------------------------------------------


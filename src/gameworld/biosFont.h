#define BIOS_FONT_CHAR_W 10
#define BIOS_FONT_CHAR_H 20

static void biosDrawChar( int ch, int x, int y )
{
    int idx = ( ch < 0 || ch > 255 ) ? 0 : ch;
    int col;

    for( col = 0; col < BIOS_FONT_CHAR_W; col++ )
      md_drawColumnPixels( x + col, y, biosFont10x20[ idx ][ col ], BIOS_FONT_CHAR_H );
}

static void biosDrawText( char* text, int x, int y )
{
    int i = 0;

    while( text[ i ] != 0 )
    {
        // codepage-1252 byte values 0x80-0xFF read back as negative through
        // a signed `char` - reinterpret as unsigned before indexing so
        // extended glyphs (accented letters etc) resolve correctly instead
        // of underflowing to a negative array index.
        int ch = (unsigned char)text[ i ];
        biosDrawChar( ch, x + i * BIOS_FONT_CHAR_W, y );
        i++;
    }
}

// Pixel width of `text` if drawn with biosDrawText() - useful for centering.
static int biosTextWidth( char* text )
{
    int len = 0;

    while( text[ len ] != 0 )
      len++;

    return len * BIOS_FONT_CHAR_W;
}


// Moved above the state-machine functions (rather than staying down in
// the "Entry points" section where it's called from) since
// crUpdateTitle() below now calls it directly - this dialect requires a
// function to be defined before its first call site, no forward
// declarations.
void crRenderFrame( void )
{
    md_beginFrame();
    int col, page;
    for( page = 0; page < 8; page++ )
      for( col = 0; col < 128; col++ )
        md_drawColumn( col, page, crFrameBuffer[ col + ( page * 128 ) ] );
}

// -----------------------------------------------------------------------------
// State setup / transitions
// -----------------------------------------------------------------------------

void crBeginSplash( void )
{
    crSplashTicks = 10; // 2000ms at this file's own 5Hz tick rate, matching upstream's real delay(2000)
    crState = CR_STATE_SPLASH;
    crSplashDirty = 1;
}

void crBeginTitle( void )
{
    crState = CR_STATE_TITLE;
    crTitleDirty = 1;
}

void crBeginPlay( void )
{
    crRestartGame();
    crState = CR_STATE_PLAY;
}

void crBeginGameOver( void )
{
    crState = CR_STATE_GAME_OVER;
    crGameOverDirty = 1;
}

// -----------------------------------------------------------------------------
// Per-tick state dispatch
// -----------------------------------------------------------------------------

void crUpdateSplash( void )
{
    // Same static-screen caching as crUpdateTitle() below - the CRASH
    // image never changes across the splash's own 10-tick hold, so it
    // only needs a real draw+render on the first tick, not all 10. The
    // countdown itself still advances every tick regardless (it's what
    // actually ends this state), matching the equivalent split already
    // used for crUpdateSplash's own timer vs. its one-time draw.
    if( crSplashDirty )
    {
        crDrawSplash();
        crSplashDirty = 0;
        crRenderFrame();
    }
    crSplashTicks = crSplashTicks - 1;
    if( crSplashTicks <= 0 ) crBeginTitle();
}

void crUpdateTitle( void )
{
    // Dirty-flag cache, added per direct user request to check for
    // optimizations on this screen: nothing on the title screen ever
    // changes while the player is just sitting on it (the high score
    // text is only ever touched right before *leaving* this state, in
    // crRestartGame()) - measured via the perf overlay at 51% CPU for
    // the one throttled tick that actually redraws it (well under the
    // 100% truncation-risk ceiling, but genuinely wasted work on every
    // subsequent ~200ms tick spent idling here). Redraw once on entry
    // (crBeginTitle() sets crTitleDirty), then skip the real draw call
    // entirely until something marks it dirty again - the same pattern
    // already established for Tiny Tris's own attract screen and every
    // obonoCoreShim game's shared isInvalid flag.
    // The dirty check alone only skips the CPU-side pixel-touching work
    // (crDrawTitle()) - the real per-tick cost also includes
    // crRenderFrame()'s own 1024 md_drawColumn() GPU blit calls, which
    // were still firing unconditionally every throttled tick regardless
    // of whether crDrawTitle() actually ran (found via a direct user
    // report that the screen was "still redrawing" even once gated).
    // Vircon32's own GPU display buffer persists whatever was last
    // drawn to it (the same standing project-wide fact every other
    // dirty-flag-cached screen already relies on - see obonoCoreShim's
    // own isInvalid-gated refreshScreen(), which skips its own flush
    // the same way) - so crRenderFrame() only needs to run on the one
    // tick that actually redrew the buffer, not every tick spent
    // idling here.
    if( crTitleDirty )
    {
        crDrawTitle();
        crTitleDirty = 0;
        crRenderFrame();
    }
    if( crFireEdge ) crBeginPlay();
}

void crUpdatePlay( void )
{
    crMoveCar();
    crUpdateSpeed();
    crDisplayPlaying();
    if( crDetectCrash() ) crBeginGameOver();
}

void crUpdateGameOver( void )
{
    // Same static-screen caching as crUpdateTitle()/crUpdateSplash() -
    // this is also a genuinely indefinite wait state (holds until the
    // player presses Fire), and the crash freeze-frame + "GAME OVER"
    // text never change while sitting on it.
    if( crGameOverDirty )
    {
        crDrawGameOver();
        crGameOverDirty = 0;
        crRenderFrame();
    }
    // Matches upstream's own gameOver() -> restartGame() -> waitForPress()
    // flow exactly: the high score is already committed and every
    // scrolling/enemy value already reset the instant the crash is
    // detected (crRestartGame() runs here, not on the next Fire press),
    // so the screen shown is a genuine freeze-frame of the crash
    // position while game state underneath has already reset - matching
    // upstream's own real "draw the crashed frame, restart state, then
    // wait" order exactly.
    if( crFireEdge )
    {
        crRestartGame();
        crBeginTitle();
    }
}

// -----------------------------------------------------------------------------
// Entry points
// -----------------------------------------------------------------------------

void gameCarRace_init( void )
{
    InitTinyJoypad();
    crTickCounter = 0;
    // Real EEPROM high-score restore - see crRestartGame()'s own header
    // comment. Matching the standard "simple 2-byte score" shape/virgin-
    // slot guard already used for 9+ other games in this project.
    crHighScore = eeprom_read_word( 0 );
    if( crHighScore == 65535 ) crHighScore = 0;
    crCarPosYCnt = 0;
    crBeginSplash();
    crDisplayClear();
}

void gameCarRace_update( void )
{
    crTickCounter = crTickCounter + 1;
    if( crTickCounter < CR_TICK_DIVISOR ) return;
    crTickCounter = 0;

    // A plain single-frame edge/level check would silently miss a real
    // button tap shorter than this tick's own ~200ms sample window
    // (confirmed via Puppeteer testing - a 100ms test-harness press
    // landed between two throttled samples and was dropped entirely,
    // exactly the risk this project's own md_recentlyPressed() helper
    // exists to close - see machineDependent.h's own comment). Using
    // it here means "was the button pressed at any point since the
    // last throttled tick ran", not just "is it down on this exact
    // sampled frame".
    crFireEdge = md_recentlyPressed( md_inputFireFrames(), CR_TICK_DIVISOR );
    crKeyUp = md_recentlyPressed( md_inputUpFrames(), CR_TICK_DIVISOR );
    crKeyDown = md_recentlyPressed( md_inputDownFrames(), CR_TICK_DIVISOR );

    // SPLASH/TITLE/GAME_OVER all render themselves internally, only on
    // the one tick they're actually dirty (see each one's own header
    // comment) - only PLAY genuinely redraws something different every
    // tick (scrolling road/enemies/score), so it's the only branch that
    // still needs an unconditional render here.
    if( crState == CR_STATE_SPLASH ) crUpdateSplash();
    else if( crState == CR_STATE_TITLE ) crUpdateTitle();
    else if( crState == CR_STATE_PLAY ) { crUpdatePlay(); crRenderFrame(); }
    else crUpdateGameOver();
}

void gameCarRace_forceRedraw( void )
{
    // Every branch draws unconditionally here regardless of its own
    // state's dirty flag (a dialog resume must always force a real
    // redraw), and clears that flag afterward so the next real tick
    // doesn't redundantly redraw the exact same content again.
    if( crState == CR_STATE_SPLASH ) { crDrawSplash(); crSplashDirty = 0; }
    else if( crState == CR_STATE_TITLE ) { crDrawTitle(); crTitleDirty = 0; }
    else if( crState == CR_STATE_PLAY ) crDisplayPlaying();
    else { crDrawGameOver(); crGameOverDirty = 0; }
    crRenderFrame();
}

int crFrameBuffer[1024];

void crDisplayClear( void )
{
    int i;
    for( i = 0; i < 1024; i++ ) crFrameBuffer[ i ] = 0;
}

// fillRect() - matches Adafruit_GFX/OLEDDisplay's own fillRect(x,y,w,h)
// semantics. Computes one bitmask per (column,page) instead of setting
// each pixel's own bit individually, the same technique already proven
// in Helicopter's own heliFillRect() - applied proactively here from
// the start rather than needing a later CPU-load retrofit, since this
// game's own drawRoad() draws up to 15 rectangles/tick.
//
// **Further hoisted per direct user push to keep checking for real
// optimizations**: the original version recomputed each page's own
// mask (a shift/subtract/shift chain) inside the per-column loop, even
// though that mask only ever depends on the rectangle's own y/h and the
// page index - never on which column is currently being written. For a
// 30-wide road-line rectangle that meant recomputing the exact same
// value up to 30 times over. Now computed once per overlapping page
// (at most 8, usually far fewer for these short, page-local rects)
// before the column loop even starts, so the hot inner loop is just an
// array lookup and an OR - the same "hoist row/rect-invariant work out
// of the inner loop" lesson already applied project-wide (Nohzdyve,
// TinY Fi, MRunnr, etc), just for a per-page mask instead of a per-row
// sprite offset.
void crFillRect( int x, int y, int w, int h )
{
    if( h <= 0 || w <= 0 ) return;
    int y2 = y + h - 1;
    int firstPage = y >> 3; if( firstPage < 0 ) firstPage = 0;
    int lastPage = y2 >> 3; if( lastPage > 7 ) lastPage = 7;
    int pageMask[8];
    int p, pageTop, pageBottom, lo, hi;
    for( p = firstPage; p <= lastPage; p++ )
    {
        pageTop = p * 8;
        pageBottom = pageTop + 7;
        lo = y; if( lo < pageTop ) lo = pageTop;
        hi = y2; if( hi > pageBottom ) hi = pageBottom;
        pageMask[ p ] = ( ( 1 << ( hi - lo + 1 ) ) - 1 ) << ( lo - pageTop );
    }
    int i, idx;
    for( i = x; i < x + w; i++ )
    {
        if( i < 0 || i > 127 ) continue;
        for( p = firstPage; p <= lastPage; p++ )
        {
            idx = i + p * 128;
            crFrameBuffer[ idx ] = crFrameBuffer[ idx ] | pageMask[ p ];
        }
    }
}

// Draws a pre-unpacked "1 int per pixel" sprite (see header comment for
// why every source table was unpacked offline rather than reproducing
// upstream's own real per-call XBM bit-unpacking loop here). Row/column
// bounds-checked per pixel so a sprite straddling the left/right/top/
// bottom edge (every enemy car does, mid-scroll) clips cleanly.
void crDrawXbm( int* data, int w, int h, int x, int y )
{
    int row, col, px, py, idx, bit, rowBase;
    for( row = 0; row < h; row++ )
    {
        py = y + row;
        if( py < 0 || py > 63 ) continue;
        bit = 1 << ( py & 7 );
        idx = ( py >> 3 ) * 128;
        rowBase = row * w; // hoisted out of the column loop - see crFillRect's own header comment for the same lesson
        for( col = 0; col < w; col++ )
        {
            if( !data[ rowBase + col ] ) continue;
            px = x + col;
            if( px < 0 || px > 127 ) continue;
            crFrameBuffer[ idx + px ] = crFrameBuffer[ idx + px ] | bit;
        }
    }
}

void crDrawChar( int ch, int x, int y )
{
    int col, row, glyph, idx, bit, py, line, gcol, rowBase, pageBase;
    glyph = crFontIndex( ch );
    if( glyph == 99 ) return; // space - a real no-op, nothing to draw
    line = ( glyph / 16 ) * 8;
    gcol = ( glyph % 16 ) * 8;
    for( row = 0; row < 8; row++ )
    {
        py = y + row;
        if( py < 0 || py > 63 ) continue;
        bit = 1 << ( py & 7 );
        rowBase = ( line + row ) * 128 + gcol;
        pageBase = ( py >> 3 ) * 128 + x;
        for( col = 0; col < 8; col++ )
        {
            if( x + col < 0 || x + col > 127 ) continue;
            if( !crFontData[ rowBase + col ] ) continue;
            idx = pageBase + col;
            crFrameBuffer[ idx ] = crFrameBuffer[ idx ] | bit;
        }
    }
}

// char*, not int*: Vircon32 string literals are int[] (one word per
// character) - a standard C literal is char[], so keeping these as int*
// would silently reinterpret the string's bytes 4-at-a-time as garbage
// ints. Both callers (crDrawTitle()'s "HIGH SCORE "/itoa() buffer,
// crDrawSplash()/crDrawGameOver()'s plain literals) already pass real
// char data, matching every other port's own established fix for this
// exact dialect gotcha.
void crDrawString( char* text, int x, int y )
{
    int i = 0;
    while( text[ i ] != 0 )
    {
        crDrawChar( text[ i ], x + ( 8 * i ), y );
        i = i + 1;
    }
}

void crDrawCentered( char* text, int y )
{
    int len = 0;
    while( text[ len ] != 0 ) len = len + 1;
    int x = ( 128 - len * 8 ) / 2;
    crDrawString( text, x, y );
}


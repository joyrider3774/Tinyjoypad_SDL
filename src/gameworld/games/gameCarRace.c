//
// Ported from `more games/Esp8266OledGame/src/CarRaceGame.h`/`.cpp` -
// one of 4 games bundled in this ESP8266+1.3" SH1106 OLED handheld
// project (see this file's own "sixth beyond-scope discovery pass"
// history for how the bundle was found and triaged). The other 3
// (FlappyBirdGame/PongGame/TRexGame) were confirmed via a quick read to
// be genre-duplicates of already-shipped titles (Flappy Bird/Pipe Bird,
// Bat Bonanza/Laser Pong, Dino Game respectively) and were not ported -
// this is the one genuinely new genre in the bundle: a top-down,
// fixed-position lane-dodging traffic racer (steer a car between 4
// horizontal lanes, dodge 3 independently-scrolling enemy cars),
// structurally distinct from Road Rush's own pseudo-3D perspective
// racer already shipped from a different bundle/author entirely.
//
// Real hardware confirmed via `lib/OledMenu/A_config.h` (the file
// actually compiled - `src/A_config.h` is a dead, entirely-commented-out
// placeholder, checked directly rather than assumed): an SH1106 128x64
// OLED (this project's own standing "functionally equivalent to
// SSD1306" treatment applies, same page-byte model, no new handling
// needed) and exactly 3 real buttons (Up/Down/A, no dedicated second
// fire button) - matching several other beyond-scope 3-button-only
// ports in this project. Not `tinyJoypadShim`/`obonoCoreShim` lineage -
// needed no new shim: `isUpPressed()`/`isDownPressed()` cover the whole
// lane-switch input surface (`moveCar()`'s own DIRRIGHT/DIRLEFT naming
// is a real, if confusing, upstream artifact - traced through by hand
// rather than assumed: DIRRIGHT is wired to the Up button and moves the
// car toward lane 0/the top of the screen; DIRLEFT is wired to Down and
// moves it toward lane 3/the bottom - a plain, intuitive up/down
// mapping once actually followed through, nothing to remap).
// `isFirePressed()` covers the "press any key" attract-screen dismissal/
// restart gesture (matched to Button A, upstream's own third button,
// which otherwise only triggers an exit-confirmation dialog this
// project's own Start-button quit dialog already supersedes).
//
// **A new packed-bitmap data format for this project**: every sprite
// here (`CARSPRITE`/`ENEMY0`/`ENEMY1`/`ENEMY2`/`CRASH`) is real XBM-
// packed data (LSB-first bit order, `ceil(width/8)` bytes per row),
// unlike every prior port's own pre-unpacked "1 int per pixel" bool
// arrays. Confirmed the exact unpacking convention by reading
// `OLEDDisplay.cpp`'s own real `drawXbm()` implementation directly
// rather than assuming a byte order: `data = xbm[(x/8) + y*widthInXbm]`,
// tested via `data & 0x01` then `data >>= 1` each subsequent pixel -
// standard LSB-first XBM. Unpacked offline via a small Python script
// into flat pixel arrays matching this project's own established
// convention, verified by byte count before use (`CARSPRITE`/`ENEMY0`/
// `ENEMY1`/`ENEMY2` are each confirmed 60 bytes = 4 bytes/row x 15 rows
// for a 30x15 sprite; `CRASH` is confirmed 1024 bytes = 16 bytes/row x
// 64 rows for the full 128x64 splash image) - not hand-retyped, per
// this project's own long-standing anti-transcription-bug discipline.
//
// Font: upstream's own real font table does exist in this repo's own
// source (`lib/SSD1306/src/OLEDDisplayFonts.h`'s `ArialMT_Plain_10`,
// checked directly) - but it's a genuinely different, proportional-
// width bitmap-font format (a run-length jump table keyed by ASCII
// code, variable glyph widths) than this project's own established
// fixed-width 8x8-cell "myfont" family, and the only text this game
// ever draws (a plain numeric score, "High Score: N", "Reckless"/
// "Racer"/"press any key", "GAME OVER") needs no proportional-width
// rendering to read correctly. Reused the already-verified myfont-
// family font table verbatim instead (matching Helicopter's own
// precedent, for the exact same reason - see that file's own header
// comment) rather than parsing a second, more complex font format for
// zero real gameplay/fidelity benefit.
//
// Same page-byte framebuffer layout as every other port in this
// project (`crFrameBuffer`). Every draw primitive writes directly into
// the framebuffer via inlined page/bit math from the start
// (`crFillRect()`/`crDrawXbm()`/`crDrawChar()`), `crDisplayClear()` is a
// flat 1024-word fill - applying this project's own now-standard
// "optimize proactively, don't wait for a CPU report" lesson from the
// first draft rather than retrofitting it later.
//
// **Render-order simplification, not a bug**: upstream's own
// `updateGame()` draws the road/enemies *before* `updateSpeed()` moves
// them that tick (so the frame actually flushed to the real display
// each loop iteration is one tick stale for those two layers, while the
// car/score - drawn after `updateSpeed()`, in `updateDisplay()` - are
// current). This only matters on real hardware because each
// `display.display()` call is a genuine, individually-visible I2C
// flush; this port computes the whole tick's new state first and
// renders the entire resulting frame in one pass (matching every other
// port's own established model, where draw order among non-overlapping
// layers never affects the final flushed image) - the visible end
// result is the same "smoothly stepping" scene either way, just without
// reproducing a one-tick lag that was only ever an artifact of
// upstream's own incremental single-buffer redraw order.
//
// **The real, single genuine timing driver upstream has**:
// `updateSpeed()`'s own `millis()`-gated ~200ms internal throttle (the
// only place road/enemy positions, score, and difficulty actually
// change - `moveCar()`'s own lane switch is a plain edge-triggered
// event with no real-time pacing of its own, driven by the Button
// library's real-hardware click/debounce logic, which this project's
// own standing "drop real-hardware debounce, use edge-detection"
// precedent already covers). Ported as a genuine whole-tick throttle,
// `CR_TICK_DIVISOR = 12` (60/12 = 5 ticks/sec, matching 200ms exactly) -
// gating input, movement, scrolling, and the redraw together, the same
// "gate everything, skip the whole tick" shape already established as
// this project's own generally-preferred default (see Helicopter's own
// header comment for why a movement-only/redraw-at-native-rate split is
// only worth it when something *else* needs to keep animating between
// throttled ticks - nothing here does, since nothing changes outside
// this one throttled step).
//
// Upstream's own two-screen intro sequence (a boot-time `splashScreen()`
// - the `CRASH` image held for a real, blocking 2000ms - followed by the
// real interactive `waitForPress()` title screen) is preserved as two
// distinct states, `CR_STATE_SPLASH` then `CR_STATE_TITLE` - and,
// matching a real, deliberate upstream structural quirk traced through
// the actual control flow rather than assumed: `gameOver()` calls
// `restartGame()` then `waitForPress()` directly, *skipping*
// `splashScreen()` entirely on every replay - only the very first entry
// into the game ever shows the crash-image splash. Reproduced exactly:
// `crBeginGameOver()` transitions straight to `CR_STATE_TITLE`, bypassing
// `CR_STATE_SPLASH`.
//
// No real EEPROM usage exists anywhere in this game's own source
// (confirmed via a direct grep of `CarRaceGame.h`/`.cpp` - no
// `<EEPROM.h>` include, no `eeprom_*` call) - `highScore` is upstream's
// own plain in-memory `long`, reset every real power-cycle. Initially
// left as session-local only, matching this project's own precedent for
// other beyond-scope ports with no genuine upstream persistence to
// restore (Meteor Storm, Flappy Bird) - **later added anyway, at direct
// user request** after a reset lost the previous high score, a
// deliberate extension beyond upstream matching this project's own
// precedent for Helicopter/Nohzdyve/Tiny Bert (see `crRestartGame()`'s
// own header comment for the actual read/write sites).
//
// `randomPosX()` is declared and defined upstream but never actually
// called anywhere in the file (confirmed by grep) - dead code, not
// ported. `checkCarPostion()` is declared but never defined or called
// anywhere either - also dropped.


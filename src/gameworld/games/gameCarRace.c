void crRestartGame( void )
{
    // Real EEPROM high-score persistence, added at direct user request
    // after a reset lost the previous session's high score - a
    // deliberate extension beyond upstream (which has none either,
    // matching this project's own precedent for Helicopter/Nohzdyve/
    // Tiny Bert), the standard "simple 2-byte score" shape used for 9+
    // other games in this project. Written here (not a separate call
    // site) since this is upstream's own single real "is this a new
    // high score" check, reused unchanged - matches every actual score
    // change (both a fresh game start and every real post-crash
    // restart, since restartGame() upstream is called from both).
    if( crScore >= crHighScore ) { crHighScore = crScore; eeprom_write_word( 0, crHighScore ); }

    crScore = 0;
    crDrawSpeed = 4;
    crCntSpeed = 0;
    crCarPosYCnt = 0;
    crRoadLineX1 = 51;
    crRoadLineX2 = 102;
    crRoadLineX3 = 153;
    crRoadLineX4 = 254;
    crRoadLineX5 = 200;
    crEnemy0PosX = 200; crEnemy0PosY = crRandomLaneY();
    crEnemy1PosX = 250; crEnemy1PosY = crRandomLaneY();
    crEnemy2PosX = 300; crEnemy2PosY = crRandomLaneY();
}

